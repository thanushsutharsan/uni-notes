# sqlite is used locally unless a real database url is supplied.
# this prevents an empty url from creating an invalid database.
database_url = os.environ.get("DATABASE_URL", "").strip()

if database_url:
    if not dj_database_url:
        raise ImportError(
            "DATABASE_URL is set but the "
            "`dj-database-url` package is not installed. "
            "Install it or unset DATABASE_URL."
        )

    DATABASES = {
        "default": dj_database_url.parse(
            database_url,
            conn_max_age=600,
            conn_health_checks=True,
        )
    }
else:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }

